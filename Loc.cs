    static Dictionary<string, string> _current = En;

    public static string Code { get; private set; } = "en";

    public static void Init(string setting)
    {
        string code = setting;
        if (code == "auto" || !Tables.ContainsKey(code))
            code = CultureInfo.CurrentUICulture.TwoLetterISOLanguageName;
        if (!Tables.ContainsKey(code)) code = "en";
        Code = code;
        _current = Tables[code];
    }

    public static string T(string key) =>
        _current.TryGetValue(key, out var v) ? v : En.TryGetValue(key, out var e) ? e : key;

    public static string T(string key, params object[] args) => string.Format(T(key), args);

